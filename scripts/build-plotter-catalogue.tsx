/// <reference types="bun-types" />

import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { concepts } from "../components/plotter/coss-concepts";
import { illustrations } from "../components/plotter/illustrations";
import {
  familyPrefix,
  type StudyCategory,
} from "../components/plotter/study-types";

// Bundle every catalogue drawing in the skill, so a brief can name a code
// (“like TIM-06”) and the installed skill can open the drawing it refers to.
const root = resolve(import.meta.dir, "..");
const exporter = resolve(root, "skills/plotter/scripts/export-svg.py");
const destination = resolve(root, "skills/plotter/references/catalogue");

// Website drawings borrow two page colors. A standalone file resolves them the
// way the bundled reference snapshots do: white paper, near-black ink.
function standalone(markup: string) {
  return markup
    .replace(/var\(--color-sidebar[^)]*\)/g, "#ffffff")
    .replace(/var\(--foreground[^)]*\)/g, "#171717");
}

type Entry = {
  code: string;
  title: string;
  description: string;
  family: string;
  markup: string;
};

const entries: Entry[] = [
  ...illustrations.map((item) => ({
    code: item.code,
    title: item.title,
    description: item.description,
    family: item.category,
    markup: standalone(renderToStaticMarkup(item.illustration)),
  })),
  ...concepts.map((concept) => ({
    code: concept.code,
    title: concept.title,
    description: concept.description,
    family: "coss.com concepts",
    markup: standalone(renderToStaticMarkup(createElement(concept.Drawing))),
  })),
];

mkdirSync(destination, { recursive: true });
for (const file of readdirSync(destination)) {
  if (file.endsWith(".svg")) rmSync(resolve(destination, file));
}

const temporary = mkdtempSync(resolve(tmpdir(), "plotter-catalogue-"));
try {
  for (const entry of entries) {
    const source = resolve(temporary, `${entry.code}.svg`);
    writeFileSync(source, entry.markup);
    execFileSync(
      "python3",
      [
        exporter,
        source,
        resolve(destination, `${entry.code}.svg`),
        "--ink",
        "#171717",
        "--id-prefix",
        entry.code.toLowerCase(),
        "--title",
        entry.title,
        "--description",
        entry.description,
      ],
      { stdio: "inherit" },
    );
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}

const families = [
  ...(Object.keys(familyPrefix) as StudyCategory[]),
  "coss.com concepts",
];
const sections = families
  .map((family) => {
    const rows = entries.filter((entry) => entry.family === family);
    if (!rows.length) return "";
    const prefix = rows[0]?.code.slice(0, 3);
    return [
      `## ${family} (${prefix})`,
      "",
      "| Code | Drawing | What it explains |",
      "| --- | --- | --- |",
      ...rows.map(
        (row) =>
          `| [${row.code}](${row.code}.svg) | ${row.title} | ${row.description} |`,
      ),
      "",
    ].join("\n");
  })
  .filter(Boolean)
  .join("\n");

writeFileSync(
  resolve(destination, "index.md"),
  `<!-- Generated by scripts/build-plotter-catalogue.tsx. Edit the catalogue sources, then run \`bun run catalogue\`. -->

# Catalogue

Every drawing in the Plotter catalogue, exported as a resolved static SVG at its native 560 × 440. Codes match the website. When a brief names a code (“like TIM-06”), open that file and borrow its construction relationship, not its subject.

Codes are a three-letter family prefix and a number, without gaps within a family. Drawings retired as near-duplicates keep their former codes in the repository’s code map and are not exported here. The [approved references](../approved-references.md) remain the style anchors; a catalogue drawing is an example, not a new reference selection.

${sections}`,
);

console.log(`Exported ${entries.length} catalogue drawings to ${destination}.`);
