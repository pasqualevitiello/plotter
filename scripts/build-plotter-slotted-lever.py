"""Compile the standalone slotted-lever SVG for the animations gallery."""

import re
import xml.etree.ElementTree as ET
from pathlib import Path

from plotter_svg import element

ROOT = Path(__file__).resolve().parents[1]
svg = ET.parse(ROOT / "examples/slotted-lever/slotted-lever.svg").getroot()
ids = [node.attrib["id"] for node in svg.iter() if "id" in node.attrib]
nodes = {node.attrib["id"]: node for node in svg.iter() if "id" in node.attrib}


def motion(node, property, attribute="transform", kind=None):
    attrs = {"animated": "__animated__", "property": property, "attributeName": attribute}
    if kind:
        attrs["type"] = kind
    ET.SubElement(node, "SlottedLeverMotion", attrs)


motion(nodes["sl-wheel"], "crank", kind="rotate")
motion(nodes["sl-lever"], "lever", kind="rotate")
motion(nodes["sl-carriage"], "carriage", kind="translate")
# SMIL animates one transform type per node; preserve the source transform order.
link = nodes["sl-link"]
translation, rotation = re.fullmatch(r"(translate\([^)]+\)) (rotate\([^)]+\))", link.attrib["transform"]).groups()
link.attrib["transform"] = translation
turn = ET.Element("g", {"transform": rotation})
turn.extend(list(link))
link[:] = [turn]
motion(link, "linkPosition", kind="translate")
motion(turn, "linkRotation", kind="rotate")
for name in ("pin", "tip"):
    for suffix in ("", "-clear"):
        node = nodes[f"sl-{name}{suffix}"]
        motion(node, f"{name}X", "cx")
        motion(node, f"{name}Y", "cy")
motion(nodes["sl-carriage-clear"], "carriageX", "cx")

body = "\n".join(
    element(node, ids, 4) for node in svg
    if node.attrib.get("data-plotter-styles") != "true"
)
body = body.replace('animated={"__animated__"}', 'animated={animated}')
source = f'''// Generated by scripts/build-plotter-slotted-lever.py from the standalone SVG.
// Edit examples/slotted-lever/drawing.mjs, rebuild its SVG, then regenerate.
import {{ useId }} from "react";
import {{ BlueprintDrawing }} from "./blueprint-drawing";
import {{ SlottedLeverMotion }} from "./slotted-lever-motion";

export function SlottedLeverDrawing({{ animated = false }}: {{ animated?: boolean }}) {{
  const id = useId();
  return (
    <BlueprintDrawing roles>
      <g strokeLinecap="butt" strokeLinejoin="round" fontWeight="400">
{body}
      </g>
    </BlueprintDrawing>
  );
}}
'''
(ROOT / "components/plotter/slotted-lever-drawing.tsx").write_text(source)
print("Compiled slotted-lever gallery drawing.")
