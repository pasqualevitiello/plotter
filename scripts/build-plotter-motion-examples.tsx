function svg(node: ReactNode, prefix: string, title: string) {
  return renderToStaticMarkup(node, { identifierPrefix: `${prefix}-` })
    .replace(/<style data-plotter-styles="true">[\s\S]*?<\/style>/g, "")
    .replace(/<svg\b[^>]*>/, (opening) => {
      const attributes = opening
        .replace(/\sclass="[^"]*"/, "")
        .replace(/\saria-hidden="true"/, "")
        .slice(0, -1);
      return `${attributes} xmlns="http://www.w3.org/2000/svg" width="560" height="440" role="img" aria-labelledby="${prefix}-title"><title id="${prefix}-title">${title}</title>`;
    });
}

